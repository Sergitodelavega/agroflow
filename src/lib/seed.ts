const zone = (n: string) => ZONES.find((z) => z.name === n)!;
const dest = (n: string) => DESTINATIONS.find((z) => z.name === n)!;

function ev(
  type: LotEvent["type"],
  daysAgo: number,
  note: string,
  vig: LotEvent["vigilance"] = "ok",
): LotEvent {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  return {
    id: `EVT-${Math.random().toString(36).slice(2, 8)}`,
    type,
    at: d.toISOString(),
    note,
    vigilance: vig,
  };
}

function iso(daysFromNow: number): string {
  const d = new Date();
  d.setDate(d.getDate() + daysFromNow);
  return d.toISOString().slice(0, 10);
}

